"""Rewrite the results block in README.md from results/summary.json and results/conjecture.csv.

Everything between <!-- RESULTS:START --> and <!-- RESULTS:END --> is regenerated,
so every experimental number in the README comes from the results files.
"""

from __future__ import annotations

import csv
import json
import math
import re

from _common import README, RESULTS

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def build_block() -> str:
    s = json.loads((RESULTS / "summary.json").read_text())
    by_n = s["by_n"]
    methods = sorted({v["method"] for v in by_n.values()})
    head = by_n[str(s["headline_n"])]
    lines = [START, "",
             f"*Generated by `scripts/update_readme.py` from `results/summary.json` and `results/conjecture.csv`. "
             f"Solver: **{', '.join(methods)}**"
             + (" (upper bound on the true SMT, so ρ values are upper bounds)." if "heuristic" in methods else ".")
             + "*", "",
             f"**Headline:** over {head['trials']:,} random {s['headline_n']}-point sets, mean ρ = "
             f"**{head['mean']:.4f}** (median {head['median']:.4f}, min {head['min']:.4f}), i.e. Steiner trees are "
             f"about {head['mean_reduction_pct']:.1f}% shorter than MSTs on average.", ""]
    p = s["plateau"]
    if p["mean"] is not None:
        lines += [f"**Large-n plateau:** pooling the {p['trials']} trials with n ≥ {p['min_n']}, mean ρ = "
                  f"**{p['mean']:.4f}**.", ""]
    lines += ["| n | trials | mean ρ | median ρ | min ρ | 10th–90th pct | mean saving | mean # Steiner pts |",
              "|---:|---:|---:|---:|---:|:---:|---:|---:|"]
    for v in by_n.values():
        lines.append(f"| {v['n']} | {v['trials']:,} | {v['mean']:.4f} | {v['median']:.4f} | {v['min']:.4f} | "
                     f"{v['p10']:.4f}–{v['p90']:.4f} | {v['mean_reduction_pct']:.2f}% | "
                     f"{v['mean_steiner_points']:.2f} |")

    with open(RESULTS / "conjecture.csv", newline="") as f:
        rows = list(csv.DictReader(f))
    best = {}
    for r in rows:
        if r["family"] not in best or float(r["rho"]) < float(best[r["family"]]["rho"]):
            best[r["family"]] = r
    lines += ["", f"**Smallest ρ per point-set family** (conjecture: ρ ≥ √3/2 ≈ {math.sqrt(3) / 2:.4f}):", "",
              "| family | n | ρ | reduction |", "|---|---:|---:|---:|"]
    for fam, r in sorted(best.items(), key=lambda kv: float(kv[1]["rho"])):
        lines.append(f"| {fam} | {r['n']} | {float(r['rho']):.4f} | {float(r['reduction_pct']):.2f}% |")
    lines += ["", END]
    return "\n".join(lines)


def main():
    text = README.read_text(encoding="utf-8")
    block = build_block()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit("README.md has no RESULTS markers")
    README.write_text(pattern.sub(lambda _: block, text), encoding="utf-8")
    print("README results block updated")


if __name__ == "__main__":
    main()
